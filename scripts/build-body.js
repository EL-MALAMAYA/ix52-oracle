function card(spec) {
    var minutes = {
        expansive: [12, 10, 4],
        ordinary: [9, 8, 2],
        constrained: [5, 4, 1],
        recovery: [2, 2, 1]
    };
    if (spec.minutes) {
        Object.keys(spec.minutes).forEach(function (key) { minutes[key] = spec.minutes[key]; });
    }
    var steps = {
        expansive: { ps: spec.eps, ms: spec.ems },
        ordinary: { ps: spec.ps, ms: spec.ms },
        constrained: { ps: spec.cps, ms: spec.cms },
        recovery: { ps: spec.rps, ms: spec.rms }
    };
    var variants = {};
    Object.keys(minutes).forEach(function (id) {
        var band = minutes[id];
        variants[id] = {
            physical_minutes: band[0],
            mental_minutes: band[1],
            rest_minutes: band[2],
            physical_steps: steps[id].ps,
            mental_steps: steps[id].ms,
            total_minutes: band[0] + band[1] + band[2]
        };
    });
    return {
        card_code: spec.code,
        physical_title: spec.pt,
        physical_description: spec.pd,
        physical_steps: spec.ps,
        mental_title: spec.mt,
        mental_description: spec.md,
        mental_steps: spec.ms,
        equipment: spec.equipment || "None. A chair is enough.",
        accessibility_alternative: spec.access,
        philosophical_connection: spec.why,
        total_duration_minutes: variants.ordinary.total_minutes,
        capacity_variants: variants
    };
}

